import assert from 'node:assert/strict';
import {readFileSync, writeFileSync, rmSync} from 'node:fs';
import {execFileSync, spawnSync} from 'node:child_process';
const branch = 'feat/p0-case-global-chart-governance-20261023';
const workflow = '.github/workflows/one-shot-block-master-growth-p0.yml';
const script = 'scripts/one-shot-block-master-growth-p0.mjs';
const expectedBlob = '3515ea68be941a263c1c0d7a19cbaa2b4ec082e7';
const git = (args) => execFileSync('git',args,{encoding:'utf8'}).trim();
const run = (cmd,args) => {
  const result=spawnSync(cmd,args,{stdio:'inherit',timeout:180000});
  assert.equal(result.status,0,cmd+' '+args.join(' ')+' failed '+String(result.error||result.status));
};
assert.equal(git(['hash-object','server.ts']),expectedBlob,'server must be exact audited staging blob');
const source=readFileSync('server.ts','utf8');
const key="app.get('/api/portal/patients/:patientId/mastery-growth'";
const start=source.indexOf(key),end=source.indexOf("app.get('/api/portal/context'",start);
assert.ok(start>0 && end>start && source.split(key).length===2,'unique legacy route');
const old="      const data = await readPatientMasteryGrowthEvents({ patientId: resolvedPatientId, clinicId: context?.clinicId });\n      return res.json({ success: true, data });";
const replaced="      // No direct clinical chart projection may bypass the selected publication.\n      // The canonical PLAN_PTS/ABA_V3 portal endpoint is /shared-chart.\n      return res.status(403).json({ success: false, error: 'GRAPH_NOT_SHARED' });";
const segment=source.slice(start,end);
assert.equal(segment.split(old).length-1,1,'legacy read occurs once in this handler');
const patched=source.slice(0,start)+segment.replace(old,replaced)+source.slice(end);
assert.equal(patched.replace(replaced,old),source,'full-server reversible one-route change');
assert.ok(patched.slice(start,patched.indexOf("app.get('/api/portal/context'",start)).includes('GRAPH_NOT_SHARED'));
writeFileSync('server.ts',patched);
run('node',['tests/patientSharedChartGovernanceP0.regression.test.mjs']);
run('git',['diff','--check']);
rmSync(workflow); rmSync(script);
run('git',['add','-A']);
const expected=[workflow,script,'server.ts'].sort().join('\n');
assert.equal(git(['diff','--cached','--name-only']).split('\n').sort().join('\n'),expected,'unexpected file modified');
run('git',['config','user.name','github-actions[bot]']);
run('git',['config','user.email','41898282+github-actions[bot]@users.noreply.github.com']);
run('git',['commit','-m','security(P0): close legacy mastery-growth portal chart bypass']);
