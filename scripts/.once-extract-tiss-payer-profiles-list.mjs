import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const branch = 'refactor/backend-tiss-payer-profiles-read-20261012';
const baseline = '5fc564ba5b11bef1f21b56e4f81fd6c43e587f60';
const expectedBlob = 'aa914fac455bbd82fab898843cdee795acccf33a';
assert.equal(process.env.GITHUB_REF, 'refs/heads/' + branch, 'feature branch only');
const git = (...args) => execFileSync('git', args, { encoding: 'utf8' }).trim();
assert.equal(git('rev-parse', 'origin/staging'), baseline, 'staging baseline changed; abort and rebase safely');
assert.equal(git('rev-parse', 'HEAD:server.ts'), expectedBlob, 'source blob changed; abort');
const original = readFileSync('server.ts', 'utf8');
const marker = "  app.get('/api/admin/tiss/payer-profiles', noStoreDynamicResponse, checkAuth, requireClinicModule('insurance_tiss'), requireClinicCapability('billing.mapping.manage'), async (req: any, res) => {";
const next = "  app.get('/api/admin/tiss/payer-profiles/:payerId', noStoreDynamicResponse, checkAuth, requireClinicModule('insurance_tiss'), requireClinicCapability('billing.mapping.manage'), async (req: any, res) => {";
const start = original.indexOf(marker);
const stop = original.indexOf(next, start);
assert.ok(start > 0 && stop > start, 'known unique route boundaries');
assert.equal(original.indexOf(marker, start + 1), -1, 'unique route');
assert.ok(!original.includes('registerTissPayerProfilesListRoute(app'), 'not already extracted');
const oldBlock = original.slice(start, stop);
assert.ok(oldBlock.endsWith('  });\n\n'), 'self-contained route');
const service = readFileSync('services/tissPayerProfilesListRoute.ts', 'utf8');
assert.ok(service.includes(oldBlock.slice(0, -2)), 'original route body and middleware copied byte-exact');

const deps = ['noStoreDynamicResponse', 'checkAuth', 'requireClinicModule', 'requireClinicCapability', 'sanitizeString', 'currentClinicId', 'isUuid', 'payerSafeError', 'supabase', 'PAYER_TISS_PROFILE_SELECT', 'PAYER_TISS_PROFILE_OPTIONAL_REVIEW_COLUMNS', 'extractMissingColumnName', 'PAYER_TISS_PROFILE_BASE_SELECT', 'hasMissingFinancialSchema', 'isMissingRelationError', 'sendNoStoreJson'];
const call = '  registerTissPayerProfilesListRoute(app, {\n' + deps.map(x => '    ' + x + ',').join('\n') + '\n  });\n\n';
const originalImport = "import express from 'express';\n";
const replacementImport = originalImport + "import { registerTissPayerProfilesListRoute } from './services/tissPayerProfilesListRoute';\n";
assert.ok(original.startsWith(originalImport), 'stable import anchor');
assert.equal(original.split(originalImport).length, 2, 'unique import');
const rewritten = (original.slice(0, start) + call + original.slice(stop)).replace(originalImport, replacementImport);
assert.equal(rewritten.replace(replacementImport, originalImport).replace(call, oldBlock), original, 'exact source reverse reconstruction');
assert.equal(original.split('\n').length - rewritten.split('\n').length, 20, '20 entrypoint lines removed');
writeFileSync('server.ts', rewritten);
console.log('Original body + protected middleware + route order preserved; 20-line server.ts reduction.');
