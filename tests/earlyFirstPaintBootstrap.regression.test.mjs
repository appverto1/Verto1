import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const html=readFileSync('index.html','utf8');
const css=readFileSync('public/boot-first-paint.css','utf8');
const entry=readFileSync('src/main.tsx','utf8');
assert.match(html,/<link rel="stylesheet" href="\/boot-first-paint\.css\?v=20261120"/);
assert.match(html,/<div id="root">\s*<!-- Static first paint/);
assert.match(html,/class="verto-boot" role="status" aria-label="Carregando Verto" aria-busy="true"/);
assert.match(html,/<header class="verto-boot-header">/);
assert.match(html,/<main class="verto-boot-hero" aria-hidden="true">/);
assert.match(html,/class="verto-boot-logo" aria-hidden="true">verto<\/span>/);
assert.match(html,/<script type="module" src="\/src\/main\.tsx"><\/script>/);
assert.match(entry,/createRoot\(document\.getElementById\('root'\)!\)\.render\(/);
assert.doesNotMatch(html,/<script[^>]*>\s*(?:(?!<\/script>).)+<\/script>/s);
assert.ok(css.length<3500);
assert.match(css,/@media\(max-width:767px\)/);
assert.match(css,/\.verto-boot-hero\{display:grid/);
assert.match(css,/\.verto-boot-preview\{display:none\}/);
assert.doesNotMatch(css,/@import|https?:\/\/|url\(/i);
assert.doesNotMatch(html,/verto-boot[^>]*on(?:click|load|error)=/i);
console.log('earlyFirstPaintBootstrap: PASS (accessible static shell, no auth/data/JS changes)');
