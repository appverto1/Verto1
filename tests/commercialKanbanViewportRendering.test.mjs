import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const source = readFileSync(new URL('../src/components/CommercialKanban.tsx', import.meta.url), 'utf8');
const column = source.split('{shownColumns.map((col)=>{')[1]?.split('          <div className="flex w-[104px]')[0];
assert.ok(column, 'existing column projection must be preserved');
const card = source.split('renderCard={lead=>{')[1]?.split('</article>;')[0];
assert.ok(card, 'full original card actions remain within the bounded window renderer');
assert.match(column, /<WindowedKanbanCards items=\{cards\} columnTitle=\{col\.title\}/, 'large columns use bounded DOM window');
const windowed=readFileSync(new URL('../src/components/WindowedKanbanCards.tsx', import.meta.url),'utf8');
assert.match(windowed, /VIRTUALIZE_AT=30/, 'small columns preserve original full rendering');
assert.match(windowed, /items\.slice\(start,end\)\.map/, 'large columns mount only the visible interval');
assert.match(windowed, /new ResizeObserver\(measure\)/, 'variable height is measured');
assert.match(windowed, /aria-posinset=\{index\+1\} aria-setsize=\{count\}/, 'screen reader position retained');
assert.match(windowed, /draggingRef\.current=true/, 'native drag keeps its source mounted');
assert.match(windowed, /Cards anteriores/, 'keyboard-accessible backward navigation');
assert.match(windowed, /Próximos cards/, 'keyboard-accessible forward navigation');
assert.match(card, /borderLeftColor: col\.color/, 'visual column status colors preserved');
assert.match(card, /draggable=\{!busyLead&&lead\.status!=='converted'\}/, 'card remains draggable');
assert.match(card, /onDragStart=\{e=>e\.dataTransfer\.setData\('text\/plain',lead\.id\)\}/);
assert.match(card, /onClick=\{\(\)=>openCard\(lead\.id\)\}/, 'original detail action preserved');
assert.match(card, /onClick=\{\(\)=>setNotesPreviewId\(/, 'notes preview preserved');
assert.match(card, /recordAttempt\(lead,'phone','no_decisor'\)/, 'attempt registration preserved');
assert.match(source, /if\(sourceColumn\)\{moveColumnTo\(sourceColumn,col\.id\);return;\}/, 'column drag preserved');
assert.match(source, /const lead=leads\.find\(x=>x\.id===id\);if\(lead\)moveLead\(lead,col\);/, 'card move preserved');
assert.match(source, /ref=\{scrollRef\} className="min-w-0 overflow-x-auto pb-2"/, 'horizontal column scroll preserved');
assert.doesNotMatch(card, /display:\s*'none'/, 'card actions must remain visible when mounted');
assert.doesNotMatch(column, /\{cards\.map\(/, 'long columns must not mount every card');
console.log('commercialKanbanViewportRendering: PASS (bounded DOM; DnD, notes, details, counts and keyboard retained)');
